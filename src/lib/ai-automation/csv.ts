/** CSV cell escaping with spreadsheet formula-injection protection (customer text is untrusted). */
export const csvCell = (v: unknown): string => {
  let s = v == null ? "" : v instanceof Date ? v.toISOString() : String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return `"${s.replace(/"/g, '""')}"`;
};
